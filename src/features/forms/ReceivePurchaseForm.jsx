import { useState } from 'react'
import { getDocument, GlobalWorkerOptions } from 'pdfjs-dist'
import Modal from '../../components/Modal'

GlobalWorkerOptions.workerSrc = new URL('pdfjs-dist/build/pdf.worker.min.mjs', import.meta.url).toString()

const amountAfter = (source, label) => source.match(new RegExp(`${label}\\s*(?:[:：-]\\s*)?(?:₹|rs\\.?|inr)?\\s*([0-9][0-9,]*(?:\\.[0-9]+)?)`, 'i'))?.[1]?.replace(/,/g, '') || ''

const extractInvoiceFields = (source) => {
  const date = source.match(/(?:invoice\s*)?date\s*[:.]?\s*(\d{1,2})[/-](\d{1,2})[/-](\d{4})/i)
  return {
    number: source.match(/(?:invoice|bill)\s*(?:no\.?|number)\s*[:.#-]*\s*([A-Z0-9][A-Z0-9/-]*)/i)?.[1] || '',
    date: date ? `${date[3]}-${date[2].padStart(2, '0')}-${date[1].padStart(2, '0')}` : '',
    taxable_amount: amountAfter(source, '(?:untaxed\\s*amount|taxable(?:\\s*value)?|sub\\s*total)'),
    cgst: amountAfter(source, 'cgst(?:\\s*@\\s*[0-9.]+%?)?'),
    sgst: amountAfter(source, 'sgst(?:\\s*/\\s*utgst)?(?:\\s*@\\s*[0-9.]+%?)?'),
    total: amountAfter(source, '(?:grand\\s*total|net\\s*amount|invoice\\s*total|total)'),
  }
}

const readPdfText = async (file) => {
  const pdf = await getDocument({ data: new Uint8Array(await file.arrayBuffer()) }).promise
  const pages = await Promise.all(Array.from({ length: pdf.numPages }, async (_, index) => {
    const page = await pdf.getPage(index + 1)
    const content = await page.getTextContent()
    return content.items.map((item) => item.str).join(' ')
  }))
  return pages.join('\n')
}

const readInvoice = async (file, onChange, onError) => {
  if (!file) {
    onChange({ number: '', date: '', taxable_amount: '', cgst: '', sgst: '', total: '' })
    return
  }
  if (file.size > 8 * 1024 * 1024) {
    onError('Supplier invoice files must be 8 MB or smaller.')
    return
  }
  try {
    let source
    if (/\.pdf$/i.test(file.name)) {
      source = await readPdfText(file)
    } else if (/\.(txt|csv|json)$/i.test(file.name)) {
      source = await file.text()
      if (/\.json$/i.test(file.name)) {
        const parsed = JSON.parse(source)
        source = Object.entries(parsed).map(([key, value]) => `${key}: ${value}`).join('\n')
      }
    } else {
      onChange({ number: '', date: '', taxable_amount: '', cgst: '', sgst: '', total: '' })
      onError('Image invoices are attached, but their text cannot be read automatically. Enter the printed values or upload a PDF invoice.')
      return
    }
    onChange(extractInvoiceFields(source))
  } catch {
    onError('The invoice could not be read automatically. It will still be attached; enter any missing printed values.')
  }
}

export default function ReceivePurchaseForm({ order, onClose, onSubmit, saving, error }) {
  const [extracted, setExtracted] = useState({ number: '', date: '', taxable_amount: '', cgst: '', sgst: '', total: '' })
  const [file, setFile] = useState(null)
  const [fileError, setFileError] = useState('')

  const readFileData = (selectedFile) => new Promise((resolve, reject) => {
    if (!selectedFile || selectedFile.size > 8 * 1024 * 1024) return resolve('')
    const reader = new FileReader()
    reader.onload = () => resolve(String(reader.result || ''))
    reader.onerror = () => reject(new Error('The invoice file could not be attached.'))
    reader.readAsDataURL(selectedFile)
  })

  async function submit(event) {
    event.preventDefault()
    const form = new FormData(event.currentTarget)
    let invoiceFileData = ''
    try {
      invoiceFileData = await readFileData(file)
    } catch (cause) {
      setFileError(cause.message)
      return
    }
    onSubmit({
      orderId: order.id,
      supplier_invoice_number: form.get('supplier_invoice_number'),
      purchase_date: form.get('purchase_date'),
      invoice_details: {
        taxable_amount: form.get('taxable_amount'),
        cgst: form.get('cgst'),
        sgst: form.get('sgst'),
        total: form.get('total'),
      },
      invoice_file_name: file?.name || '',
      invoice_file_type: file?.type || '',
      invoice_file_data: invoiceFileData,
    })
  }

  return <Modal title={`Receive purchase · ${order.order_number}`} onClose={onClose}>
    <form className="form-grid" onSubmit={submit}>
      <p className="form-hint">Upload the supplier invoice generated by the supplier. Invoice number, taxable value, GST and total are fetched from PDF, text, CSV or JSON files. Image invoices are saved but need manual values.</p>
      <label>Supplier invoice file<input type="file" accept=".pdf,.png,.jpg,.jpeg,.txt,.csv,.json" required onChange={(event) => {
        const selected = event.target.files?.[0] || null
        setFile(selected)
        setFileError('')
        readInvoice(selected, setExtracted, setFileError)
      }} /></label>
      <div className="two">
        <label>Invoice number<input name="supplier_invoice_number" defaultValue={extracted.number} key={extracted.number} maxLength="80" /></label>
        <label>Invoice date<input name="purchase_date" type="date" defaultValue={extracted.date || new Date().toISOString().slice(0, 10)} key={`date-${extracted.date}`} required /></label>
      </div>
      <div className="three">
        <label>Taxable amount<input name="taxable_amount" type="number" min="0" step="0.01" defaultValue={extracted.taxable_amount} key={`taxable-${extracted.taxable_amount}`} /></label>
        <label>CGST<input name="cgst" type="number" min="0" step="0.01" defaultValue={extracted.cgst} key={`cgst-${extracted.cgst}`} /></label>
        <label>SGST<input name="sgst" type="number" min="0" step="0.01" defaultValue={extracted.sgst} key={`sgst-${extracted.sgst}`} /></label>
      </div>
      <label>Supplier invoice total<input name="total" type="number" min="0" step="0.01" defaultValue={extracted.total} key={`total-${extracted.total}`} /></label>
      {file && <p className="form-hint">Attached: <b>{file.name}</b></p>}
      {fileError && <div className="alert error" role="alert">{fileError}</div>}
      {error && <div className="alert error" role="alert">{error}</div>}
      <div className="foot"><button type="button" className="btn" onClick={onClose}>Cancel</button><button className="btn solid" disabled={saving}>{saving ? 'Receiving…' : 'Receive and update stock'}</button></div>
    </form>
  </Modal>
}
